export const MESSAGES: Readonly<Record<InterfaceLocale, Record<MessageKey, MessageValue>>> = {
  en,
  ru,
  de,
}

/** Formats one localized message and substitutes any dynamic parameters. */
export function formatMessage(
  locale: InterfaceLocale,
  key: MessageKey,
  params: MessageParams = {},
): string {
  const message = MESSAGES[locale][key]
  return typeof message === 'function' ? message(params) : message
}
